local h = assert(loadfile("tests/PrivateGroup.lua"))("harness")
local a, b = h.make("First Friend", "ASYNC123"), h.make("Second Friend", "ASYNC123")
a.asyncJoinDelay, b.asyncJoinDelay = 1, 2
h.click(a, function(ns) ns:RequestSync(true) end)
h.pump(35)
assert(next(a.ns.privatePeers) == nil)
h.click(b, function(ns) ns:RequestSync(true) end)
h.pump(180)
assert(a.ns:IsPrivatePeer(b.key) and b.ns:IsPrivatePeer(a.key), "Asynchronous joins must discover existing members without a second click")
assert(a.ns.db.players[b.key] and b.ns.db.players[a.key], "Both explicit shares must finish after asynchronous channel join")
assert(a.ns.privateDiscoveryStatus == "Connected; ready to share")
h.run(a, function(ns)
    local name = ns:PrivateChannelName()
    assert(ns:IsPrivateChannelEvent(nil, "3. " .. name))
    assert(ns:IsPrivateChannelEvent(nil,nil,nil,nil,nil,nil,name:lower()))
    assert(not ns:IsPrivateChannelEvent("3. Trade", name .. "OTHER"))
    ns:Emit("CHAT_MSG_CHANNEL_NOTICE", "WRONG_PASSWORD", nil, nil, "3. " .. name)
    assert(ns.privateDiscoveryStatus == "Channel error: WRONG_PASSWORD")
end)
local c = h.make("Wrong Code", "OTHER123")
c.asyncJoinDelay = 1
h.click(c, function(ns) ns:RequestSync(true) end)
h.pump(80)
assert(not a.ns:IsPrivatePeer(c.key) and not a.ns.db.players[c.key])
assert(not c.ns:IsPrivatePeer(a.key) and not c.ns.db.players[a.key])
print("PASS: real asynchronous channel join, numbered/raw channel event formats, single-click discovery, two-way explicit publication, wrong-code isolation and visible channel errors")
